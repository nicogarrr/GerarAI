"""Textos de las alertas DCA (titulo, mensaje, correo HTML), en espanol o ingles.

Modulo puro: recibe el diccionario ``dca`` que el servicio guarda en
``ResearchAlert.metadata_["dca"]`` y devuelve texto. Imita la estructura del
correo de DCA Optimizer (titular, badge del nivel en su color, zona, estado
del mes, fecha de senal y cierre asentado) con las metricas de la formula
propia. Solo muestra lo que existe: una metrica ausente no se pinta.

``language`` ("es" por defecto) es el idioma guardado del usuario al disparar
la alerta; con "en" todo el texto sale en ingles y el espanol no cambia.
"""

from __future__ import annotations

from html import escape
from typing import Any

from app.services.display_es import MESES_ES, fecha_es
from app.services.email_delivery import EmailContent

DISCLAIMER = "Apoyo a la decisión, no asesoramiento financiero."

STATUS_LABELS = {"forming": "mes en formación", "confirmed": "mes confirmado"}

DISCLAIMER_EN = "Decision support, not financial advice."
STATUS_LABELS_EN = {"forming": "month still forming", "confirmed": "month confirmed"}
FORMING_NOTE = "El mes aún no ha cerrado: el veredicto puede cambiar hasta el último cierre del mes."
FORMING_NOTE_EN = "The month has not closed yet: the verdict can change until the month's last close."
FOOTER = "Señal generada por GerarAI con la fórmula DCA propia a partir de cierres diarios asentados."
FOOTER_EN = "Signal generated by GerarAI with its own DCA formula from settled daily closes."

# Nombres de nivel y zona que guarda el motor (dca_signal_engine.LEVELS), en ingles.
LABELS_EN = {"RECORTE LIGERO": "LIGHT TRIM", "RECORTE FUERTE": "STRONG TRIM"}
ZONES_EN = {
    "Zona de compra extrema": "Extreme buy zone",
    "Zona de compra fuerte": "Strong buy zone",
    "Zona de compra": "Buy zone",
    "Zona de aportacion normal": "Normal contribution zone",
    "Zona de recorte ligero": "Light trim zone",
    "Zona de recorte fuerte": "Strong trim zone",
}
MONTHS_EN = ("Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec")


def _en(language: str | None) -> bool:
    return language == "en"


def level_label(label: Any, language: str = "es") -> str:
    text = str(label or "")
    return LABELS_EN.get(text, text) if _en(language) else text


def short_date(value: Any, language: str) -> str:
    """Fecha corta; en ingles se traduce solo el mes de ``fecha_es`` (mismo dia de Madrid)."""
    text = fecha_es(value)
    parts = text.split(" ")
    if _en(language) and len(parts) == 3 and parts[1] in MESES_ES:
        return f"{parts[0]} {MONTHS_EN[MESES_ES.index(parts[1])]} {parts[2]}"
    return text


def currency_label(currency: str | None, language: str = "es") -> str | None:
    """Codigo de divisa visible. Las lineas de Londres cotizan en peniques."""
    if not currency:
        return None
    code = currency.strip()
    if code in {"GBX", "GBp", "GBx"}:
        return "GBX (pence)" if _en(language) else "GBX (peniques)"
    return code.upper()


def number_es(value: float, decimals: int = 2, language: str = "es") -> str:
    text = f"{value:,.{decimals}f}"
    if _en(language):
        return text
    return text.replace(",", "@").replace(".", ",").replace("@", ".")


def price_es(value: float | None, currency: str | None, language: str = "es") -> str | None:
    if value is None:
        return None
    label = currency_label(currency, language)
    decimals = 2 if abs(value) >= 1 else 4
    number = number_es(float(value), decimals, language)
    return f"{number} {label}" if label else number


def percent_es(value: float | None, decimals: int = 1, language: str = "es") -> str | None:
    if value is None:
        return None
    number = number_es(float(value) * 100, decimals, language)
    return f"{number}%" if _en(language) else f"{number} %"


def is_drop(dca: dict[str, Any]) -> bool:
    """Aviso de bajada de nivel (informativo, no una senal nueva)."""
    return dca.get("direction") == "down"


def title(dca: dict[str, Any], language: str = "es") -> str:
    label = level_label(dca["label"], language)
    previous = level_label(dca.get("previous_label"), language) or None
    if is_drop(dca):
        if _en(language):
            suffix = f" (from {previous})" if previous else ""
            return f"{dca['symbol']} drops to {label}{suffix}"
        suffix = f" (desde {previous})" if previous else ""
        return f"{dca['symbol']} baja a {label}{suffix}"
    if _en(language):
        return f"{dca['symbol']} entered {label}"
    return f"{dca['symbol']} entró en {label}"


def drop_note(dca: dict[str, Any], language: str = "es") -> str | None:
    if not is_drop(dca):
        return None
    label = level_label(dca["label"], language)
    previous = level_label(dca.get("previous_label"), language) or None
    if _en(language):
        origin = f" from {previous}" if previous else ""
        return f"For your information: the level drops{origin} to {label}."
    origin = f" desde {previous}" if previous else ""
    return f"Aviso informativo: el nivel baja{origin} a {label}."


def signal_metric(dca: dict[str, Any], language: str = "es") -> tuple[str, str] | None:
    """(etiqueta, valor) de la metrica que decide el nivel de compra."""
    en = _en(language)
    metrics = dca.get("metrics") or {}
    if metrics.get("signal") == "sma_gap" and metrics.get("sma_gap") is not None:
        months = dca.get("sma_months")
        if en:
            label = f"Gap below {months}m average" if months else "Gap below long average"
        else:
            label = f"Distancia bajo media {months}m" if months else "Distancia bajo media larga"
        return label, percent_es(metrics["sma_gap"], language=language) or ""
    if metrics.get("drawdown") is not None:
        months = dca.get("high_lookback_months")
        if en:
            label = f"Drop from {months}m high" if months else "Drop from high"
        else:
            label = f"Caída desde máximo {months}m" if months else "Caída desde máximo"
        return label, percent_es(metrics["drawdown"], language=language) or ""
    return None


def detail_rows(dca: dict[str, Any], language: str = "es") -> list[tuple[str, str]]:
    """Filas etiqueta/valor comunes al texto plano y al HTML."""
    en = _en(language)
    rows: list[tuple[str, str]] = []
    zone = str(dca.get("zone") or "")
    rows.append(("Zone" if en else "Zona", ZONES_EN.get(zone, zone) if en else zone))
    statuses = STATUS_LABELS_EN if en else STATUS_LABELS
    rows.append(("Status" if en else "Estado", statuses.get(str(dca.get("status")), str(dca.get("status") or ""))))
    if dca.get("signal_date"):
        rows.append(("Signal date" if en else "Fecha de señal", short_date(dca["signal_date"], language)))
    close = price_es(dca.get("close"), dca.get("currency"), language)
    if close:
        rows.append(("Settled close" if en else "Cierre asentado", close))
    metric = signal_metric(dca, language)
    if metric:
        rows.append(metric)
    rsi = (dca.get("metrics") or {}).get("rsi")
    if rsi is not None:
        rows.append(("Monthly RSI" if en else "RSI mensual", number_es(float(rsi), 1, language)))
    prices = dca.get("level_prices") or {}
    for key in ("2x", "3x", "4x"):
        value = price_es(prices.get(key), dca.get("currency"), language)
        if value:
            rows.append((f"Close that would trigger {key.upper()}" if en else f"Cierre que activaría {key.upper()}", value))
    sources = dca.get("sources") or []
    if sources:
        names = {"watchlist": "watchlist", "portfolio": "portfolio" if en else "cartera"}
        rows.append(("Source" if en else "Origen", " + ".join(names.get(str(s), str(s)) for s in sources)))
    return rows


def message_text(dca: dict[str, Any], language: str = "es") -> str:
    en = _en(language)
    lines = [title(dca, language)]
    if dca.get("company_name"):
        lines.append(str(dca["company_name"]))
    lines.append("")
    note = drop_note(dca, language)
    if note:
        lines += [note, ""]
    lines += [f"{label}: {value}" for label, value in detail_rows(dca, language)]
    if dca.get("status") == "forming":
        lines += ["", FORMING_NOTE_EN if en else FORMING_NOTE]
    lines += ["", DISCLAIMER_EN if en else DISCLAIMER]
    return "\n".join(lines)


def email_content(dca: dict[str, Any], language: str = "es") -> EmailContent:
    en = _en(language)
    headline = title(dca, language)
    color = str(dca.get("color") or "#FFFFFF")
    fg = str(dca.get("fg") or "#000000")
    company = dca.get("company_name")
    rows_html = "".join(
        "<tr>"
        f"<td style=\"padding:6px 12px 6px 0;color:#555;font-size:13px\">{escape(label)}</td>"
        f"<td style=\"padding:6px 0;font-size:13px;font-weight:600\">{escape(value)}</td>"
        "</tr>"
        for label, value in detail_rows(dca, language)
    )
    forming_note = (
        f"<p style=\"font-size:12px;color:#555;margin:12px 0 0\">{escape(FORMING_NOTE_EN if en else FORMING_NOTE)}</p>"
        if dca.get("status") == "forming"
        else ""
    )
    html = (
        f"<!doctype html><html lang=\"{'en' if en else 'es'}\"><body style=\"margin:0;background:#0b0b0f\">"
        "<div style=\"max-width:560px;margin:0 auto;padding:24px;font-family:Arial,Helvetica,sans-serif;"
        "background:#ffffff;color:#111\">"
        f"<h1 style=\"font-size:22px;margin:0 0 4px\">{escape(headline)}</h1>"
        + (f"<p style=\"margin:0 0 16px;color:#555\">{escape(str(company))}</p>" if company else "")
        + f"<span style=\"display:inline-block;padding:6px 14px;border-radius:999px;background:{escape(color)};"
        f"color:{escape(fg)};font-weight:700;border:1px solid #d0d0d0\">{escape(level_label(dca['label'], language))}</span>"
        + (f"<p style=\"margin:12px 0 0;color:#555\">{escape(drop_note(dca, language) or '')}</p>" if is_drop(dca) else "")
        + f"<table style=\"margin-top:16px;border-collapse:collapse\">{rows_html}</table>"
        + forming_note
        + f"<p style=\"font-size:11px;color:#777;margin:20px 0 0\">{escape(DISCLAIMER_EN if en else DISCLAIMER)} "
        f"{escape(FOOTER_EN if en else FOOTER)}</p>"
        "</div></body></html>"
    )
    subject = f"{headline}" + (f" · {company}" if company else "")
    return EmailContent(subject=subject[:250], text=message_text(dca, language), html=html)
